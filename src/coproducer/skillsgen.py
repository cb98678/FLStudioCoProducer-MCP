def _doc(path: Path, name: str) -> str:
    try:
        tree = ast.parse((path / (name + ".py")).read_text(encoding="utf-8"))
        return ast.get_docstring(next(n for n in tree.body if isinstance(n, ast.FunctionDef) and not n.name.startswith("_"))) or ""
    except (OSError, StopIteration, SyntaxError):
        return ""


def _errors(doc: str) -> str:
    return ", ".join(sorted(set(re.findall(r"E_[A-Z_]+", doc))))


def _args(schema: dict) -> str:
    req = set(schema.get("required", []))
    return ", ".join("%s%s: %s" % (k, "*" if k in req else "", v.get("type", "any")) for k, v in schema.get("properties", {}).items()) or "none"


def render_layer(reg: Registry, layer: str) -> str:
    rows = sorted((m for m in reg.modules.values() if m.layer == layer and m.expose), key=lambda m: m.name)
    out = ["# Catalog: %s (generated by coproducer gen; do not edit)" % layer, "",
           "Arguments marked * are required. Autonomy A0 read, A1 needs approval, A2 acts in the sandbox.", "",
           "| Tool | What it does | Auto | Effect | Verifier | Arguments | Errors |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for m in rows:
        pol = m.manifest["policy"]
        out.append("| `%s` | %s | %s | %s | %s | %s | %s |" % (m.name, m.summary, m.autonomy, m.side_effect, pol["verifier"], _args(m.input_schema),
                                                         _errors(_doc(m.path, m.name)) or "-"))
    return "\n".join(out) + "\n"


def render_index(reg: Registry) -> str:
    out = ["# Tool index (generated by coproducer gen; do not edit)", "", "## Phase slices", ""]
    out += ["- %s: %s" % (p, ", ".join("`%s`" % n for n in names)) for p, names in SLICES.items()]
    out += ["", "On demand (ask with `request_tool`): " + ", ".join("`%s`" % n for n in ON_DEMAND), "", "## Meta tools (always on fl-bridge)", ""]
    out += ["- `%s`: %s" % (n, d) for n, (d, _, _) in meta_tools.META.items()]
    return "\n".join(out) + "\n"


def render_rules() -> str:
    return "# Module rules (generated by coproducer gen; do not edit)\n\n" + "\n".join("- **%s** %s" % kv for kv in RULES.items()) + "\n"


def render_examples(home: Path) -> str:
    """Two accepted modules with their cards: a pure one and one that writes FL state."""
    out = ["# Worked examples (generated by coproducer gen; do not edit)", ""]
    for card, layer_dir, name in (("01_encode_sysex", "l0_transport", "encode_sysex"), ("04_set_track_volume_verified", "l2_verified", "set_track_volume_verified")):
        d = home / "modules" / layer_dir / name
        out += ["## Card", "", (home / "cards" / "calibration" / (card + ".card.md")).read_text(encoding="utf-8"), ""]
        for f, lang in ((name + ".py", "python"), ("module.toml", "toml"), ("test_%s.py" % name, "python")):
            out += ["### " + f, "", "```" + lang, (d / f).read_text(encoding="utf-8").rstrip(), "```", ""]
    return "\n".join(out)


def generate(home: Path, skills_dir: Path | None = None) -> list:
    """Write references/catalog/ for every skill. Returns the files written."""
    reg, root, written = Registry(home / "modules").load(), skills_dir or home / "skills", []
    for skill, layers in SKILL_LAYERS.items():
        cat = root / skill / "references" / "catalog"
        cat.mkdir(parents=True, exist_ok=True)
        files = {"index.md": render_index(reg)}
        files.update({"%s.md" % layer: render_layer(reg, layer) for layer in layers})
        if skill == "module-authoring":
            files["rules.md"] = render_rules()
            (root / skill / "references" / "worked-examples.md").write_text(render_examples(home), encoding="utf-8", newline="\n")
            written.append(str(root / skill / "references" / "worked-examples.md"))
        for name, text in files.items():
            (cat / name).write_text(text, encoding="utf-8", newline="\n")
            written.append(str(cat / name))
    return written


