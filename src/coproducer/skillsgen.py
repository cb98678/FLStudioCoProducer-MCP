IDENT = re.compile(r"`([a-z][a-z0-9]*(?:_[a-z0-9]+)+)`")


def drift(home: Path, skills_dir: Path | None = None, allowed: set | None = None) -> dict:
    """{skill: [names]} for backticked snake_case names in SKILL.md and hand-written references that are not modules, meta tools or allowed words."""
    reg = Registry(home / "modules").load()
    known = set(reg.modules) | set(meta_tools.META) | set(VERIFIER_NAMES) | WORDS | (allowed or set())
    bad = {}
    for md in sorted((skills_dir or home / "skills").glob("*/**/*.md")):
        if "catalog" in md.parts or "generated by coproducer gen" in md.read_text(encoding="utf-8")[:200]:
            continue
        names = sorted(set(IDENT.findall(md.read_text(encoding="utf-8"))) - known)
        if names:
            bad.setdefault(md.relative_to(skills_dir or home / "skills").parts[0], []).extend("%s: %s" % (md.name, n) for n in names)
    return bad
