"""Text of the piano roll script that writes notes (route N1). It runs inside FL Studio, so the output is Python 3.9 compatible.

API names come from the official stubs (https://il-group.github.io/FL-Studio-API-Stubs/piano_roll_scripting/): flpianoroll.Note
(number, time and length in ticks, velocity 0 to 1, pan 0 to 1), flpianoroll.score (PPQ, clearNotes(all), addNote, noteCount as a property).
The createDialog/apply structure is the one the factory scripts use. Confirmed on FL 26.1.7: PPQ is 96, addNote/getNote/deleteNote read back exactly,
and the script can write files only in the Piano roll scripts folder (its working directory).
"""
from __future__ import annotations

import json

TEMPLATE = '''# GENERATED by coproducer. Writes %(count)d notes into the open piano roll.
import json
import os
import flpianoroll as flp

NOTES = %(notes)s
CLEAR = %(clear)s
RESULT_NAME = %(result)s


def createDialog():
    return flp.ScriptDialog("Coproducer notes", "Writes %(count)d notes. Press Accept.")


def apply(form):
    ppq = flp.score.PPQ
    if CLEAR:
        flp.score.clearNotes(True)
    first = flp.score.noteCount
    for n in NOTES:
        note = flp.Note()
        note.number = int(n[0])
        note.time = int(round(n[1] * ppq))
        note.length = max(1, int(round(n[2] * ppq)))
        note.velocity = float(n[3])
        note.pan = float(n[4])
        flp.score.addNote(note)
    total = flp.score.noteCount
    got = []
    for i in range(first, total):
        r = flp.score.getNote(i)
        got.append([r.number, r.time, r.length, round(r.velocity, 4)])
    report = {"expected": len(NOTES), "written": total - first, "total": total, "ppq": ppq, "notes": got}
    try:
        with open(os.path.join(os.getcwd(), RESULT_NAME), "w") as f:
            f.write(json.dumps(report))
    except Exception as e:
        print("coproducer: could not write the result file:", e)
    print("coproducer: wrote", report["written"], "of", report["expected"], "notes")
'''


def render_script(notes: list, clear_first: bool, result_name: str) -> str:
    """notes are [midi_number, start_beats, length_beats, velocity_0_to_1, pan_0_to_1] rows.

    The result file is written next to the script: FL's script Python can only write in its own folder (measured on 26.1.7).
    """
    return TEMPLATE % {"count": len(notes), "notes": json.dumps(notes), "clear": "True" if clear_first else "False",
                       "result": json.dumps(result_name)}
