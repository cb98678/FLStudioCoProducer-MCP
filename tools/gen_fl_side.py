"""Generate fl_side/device_coproducer.py: the single file that runs inside FL Studio.

One job: inline result.py, the mini JSON codec, the L0 pure modules the dispatcher needs, every L1 op, an OPS
table, and the handler template into one Python 3.9 compatible file, then syntax-check it for 3.9.
Run: python tools/gen_fl_side.py
"""
from __future__ import annotations

import ast
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src" / "coproducer"
MODS = REPO / "modules"
L0_NEEDED = ["encode_sysex", "decode_sysex", "split_frames", "build_frame", "parse_frame", "encode_body", "decode_body"]
HEADER = '''# name=Coproducer
# supportedDevices=Coproducer
# GENERATED by tools/gen_fl_side.py. Do not edit; change the sources and regenerate.
"""FL Studio side of the Coproducer bridge: receives SysEx requests, runs L1 ops, replies with SysEx."""
from __future__ import annotations

'''


def split_source(text: str) -> tuple[list[str], str]:
    """Return (hoisted import lines, source without any import or __future__ lines and without docstring)."""
    tree = ast.parse(text)
    lines = text.splitlines()
    drop: set[int] = set()
    hoist: list[str] = []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            span = range(node.lineno, (node.end_lineno or node.lineno) + 1)
            mod = getattr(node, "module", None) or ""
            names = [a.name for a in node.names]
            if not (mod.startswith("coproducer") or mod == "__future__" or any(n.startswith("coproducer") for n in names)):
                hoist.append(ast.get_source_segment(text, node) or "")
            drop.update(span)
    if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(getattr(tree.body[0], "value", None), ast.Constant) \
            and isinstance(tree.body[0].value.value, str):
        drop.update(range(tree.body[0].lineno, (tree.body[0].end_lineno or tree.body[0].lineno) + 1))
    kept = [ln for i, ln in enumerate(lines, 1) if i not in drop]
    return hoist, "\n".join(kept).strip("\n")


def top_level_names(src: str) -> dict[str, str]:
    out = {}
    for n in ast.parse(src).body:
        if isinstance(n, (ast.FunctionDef, ast.ClassDef)):
            out[n.name] = ast.get_source_segment(src, n) or ""
        elif isinstance(n, ast.Assign) and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name):
            out[n.targets[0].id] = ast.get_source_segment(src, n) or ""
    return out


def raw_allow() -> list[str]:
    p = REPO / "fl_side" / "raw_allowlist.txt"
    lines = p.read_text(encoding="utf-8").splitlines() if p.exists() else []
    return sorted({ln.strip() for ln in lines if ln.strip() and not ln.strip().startswith("#")})


def build() -> str:
    parts: list[tuple[str, str]] = []
    hoists: list[str] = ["import json  # replaced by a shim below if unavailable"]
    files: list[tuple[str, Path]] = [("result.py", SRC / "result.py"), ("fl_minijson.py", SRC / "fl_minijson.py"),
                                     ("fl_prelude.py", SRC / "fl_prelude.py"), ("fl_probes.py", SRC / "fl_probes.py")]
    for n in L0_NEEDED:
        files.append((f"L0 {n}", MODS / "l0_transport" / n / f"{n}.py"))
    for d in sorted((MODS / "l1_fl_ops").glob("op_*")):
        files.append((f"L1 {d.name}", d / f"{d.name}.py"))
    seen: dict[str, str] = {}
    for label, path in files:
        h, body = split_source(path.read_text(encoding="utf-8"))
        if label == "fl_prelude.py":
            body = body.replace("_RAW_ALLOW = set()", "_RAW_ALLOW = set(%r)" % (raw_allow(),))
        hoists += [x for x in h if x and x != "import json"]
        for name, seg in top_level_names(body).items():
            if name in seen and seen[name] != seg:
                raise SystemExit(f"conflicting top-level name {name!r} (in {label})")
            if name in seen:
                body = body.replace(seg, f"# {name} already defined above", 1)
            seen[name] = seg
        parts.append((label, body))
    uniq = sorted(set(x for x in hoists if x != "import json  # replaced by a shim below if unavailable"))
    l1_ops = sorted(n for n in seen if n.startswith("op_"))
    shim = ("try:\n    import json\nexcept ImportError:\n    class json:  # minimal stand-in\n"
            "        dumps = staticmethod(_mj_dumps)\n        loads = staticmethod(_mj_loads)\n")
    out = [HEADER, "\n".join(uniq), ""]
    for label, body in parts:
        out.append(f"\n# ---- {label}\n{body}\n")
        if label == "fl_minijson.py":
            out.append(shim)
    ops = ",\n".join(f'    "{n}": {n}' for n in l1_ops)
    ops += ',\n    "bridge_echo": _builtin_echo,\n    "bridge_config": _builtin_config,\n    "bridge_info": _builtin_info,\n    "bridge_probe": _builtin_probe'
    tmpl = (SRC / "fl_template.py").read_text(encoding="utf-8")
    _, tbody = split_source(tmpl)
    out.append("\n# ---- handler\n" + tbody + "\n")
    out.append(f"\nOPS = {{\n{ops},\n}}\n")
    return "\n".join(out)


def main() -> int:
    text = build()
    ast.parse(text, feature_version=(3, 9))
    target = REPO / "fl_side" / "device_coproducer.py"
    target.parent.mkdir(exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target} ({len(text.splitlines())} lines, {text.count('def op_')} ops)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
